#!/usr/bin/env python3
# Generates engine/geo-data.js: compact airport coordinate pack + land bitmask.
# Sources (public domain / CC0): OurAirports airports.csv, Natural Earth 110m land.
import base64, csv, io, json, os, re, sys, urllib.request
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'tools', 'data')
os.makedirs(DATA, exist_ok=True)

AIRPORTS_URL = 'https://davidmegginson.github.io/ourairports-data/airports.csv'
LAND_URL = 'https://d2ad6b4ur7yvpq.cloudfront.net/naturalearth-3.3.0/ne_110m_land.geojson'

csv_path = os.path.join(DATA, 'airports.csv')
geo_path = os.path.join(DATA, 'ne_110m_land.geojson')
if not os.path.exists(csv_path):
    print('downloading airports.csv ...')
    urllib.request.urlretrieve(AIRPORTS_URL, csv_path)
if not os.path.exists(geo_path):
    print('downloading land geojson ...')
    urllib.request.urlretrieve(LAND_URL, geo_path)

B36 = '0123456789abcdefghijklmnopqrstuvwxyz'


def b36(n):
    return B36[n // 36] + B36[n % 36]


# ---- airports (only entries with a 4-letter ICAO code, real airports) ----
rows = list(csv.DictReader(open(csv_path, encoding='utf-8')))
seen = {}
for r in rows:
    if r.get('type') not in ('large_airport', 'medium_airport', 'small_airport', 'seaplane_base', 'heliport'):
        continue
    code = ''
    for k in ('icao_code', 'gps_code', 'ident'):
        v = (r.get(k) or '').strip().upper()
        if re.fullmatch(r'[A-Z]{4}', v):
            code = v
            break
    if not code:
        continue
    try:
        lat, lon = float(r['latitude_deg']), float(r['longitude_deg'])
    except (KeyError, ValueError):
        continue
    if not (-90 <= lat <= 90 and -180 <= lon <= 180):
        continue
    seen.setdefault(code, (lat, lon))

B36 = '0123456789abcdefghijklmnopqrstuvwxyz'


def b36_5(n):
    out = ''
    for i in range(5):
        out = B36[n % 36] + out
        n //= 36
    return out


pack = []
for code in sorted(seen):
    lat, lon = seen[code]
    li = max(0, min(1800, int(round((lat + 90) / 180 * 1800))))
    gi = max(0, min(3600, int(round((lon + 180) / 360 * 3600))))
    pack.append(code + b36_5(li * 3601 + gi))
airports = ''.join(pack)
print('airports:', len(pack), 'pack chars:', len(airports))

# ---- land mask at 0.2 degrees (1800 x 900), stored row-major bits (LSB first) ----
W, H = 1800, 900
img = Image.new('1', (W, H), 0)
drw = ImageDraw.Draw(img)
gj = json.load(open(geo_path, encoding='utf-8'))


def to_xy(lon, lat):
    return ((lon + 180) / 360 * W, (90 - lat) / 180 * H)


for feat in gj['features']:
    geom = feat.get('geometry') or {}
    geoms = geom.get('coordinates') or []
    if geom.get('type') == 'Polygon':
        polys = [geoms]
    elif geom.get('type') == 'MultiPolygon':
        polys = geoms
    else:
        continue
    for poly in polys:
        for ring in poly:
            pts = [to_xy(p[0], p[1]) for p in ring if len(p) >= 2]
            if len(pts) >= 3:
                drw.polygon(pts, fill=1)

bits = np.packbits(np.array(img, dtype=np.uint8).ravel(), bitorder='little').tobytes()
land = base64.b64encode(bits).decode()
print('land mask bytes:', len(bits), 'b64 chars:', len(land))

# ---- coastline rings (for crisp outlines, incl. small islands) ----
def b36_3(n):
    return B36[n // 1296] + B36[(n // 36) % 36] + B36[n % 36]

coast_parts = []
for feat in gj['features']:
    geom = feat.get('geometry') or {}
    polys = ([geom['coordinates']] if geom.get('type') == 'Polygon'
             else geom.get('coordinates') if geom.get('type') == 'MultiPolygon' else [])
    for poly in polys:
        for ring in poly:
            pts = []
            for p in ring:
                if len(p) < 2:
                    continue
                li = max(0, min(16383, int(round((p[1] + 90) / 180 * 16383))))
                gi = max(0, min(16383, int(round((p[0] + 180) / 360 * 16383))))
                pts.append(b36_3(li) + b36_3(gi))
            if len(pts) >= 3:
                coast_parts.append(''.join(pts))
coast = '-'.join(coast_parts)
print('coast rings:', len(coast_parts), 'chars:', len(coast))

out = os.path.join(ROOT, 'engine', 'geo-data.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write("/* auto-generated by tools/build-geo.py - OurAirports (public domain) + Natural Earth (CC0) */\n")
    f.write("window.JP_GEO={airports:'%s',land:'%s',lw:%d,lh:%d,coast:'%s'};\n" % (airports, land, W, H, coast))
print('wrote', out, os.path.getsize(out), 'bytes')
